## Using this website

This website is provided by Ẹgbẹ́ Bobagunwa Okunrin Akile Ijebu to share information about the association and to support its members. Public pages may be read by anyone.

## Member and officer accounts

- Accounts are created only for approved members and authorised officers. Public registration is not available.
- Keep your password private. Do not share your account; officers must always use their own named account.
- Tell the secretariat promptly if you believe someone else has used your account.
- The association may suspend access to protect members’ information or the association’s records.

## Records and payments

Financial records shown in the portal reflect payments that the association has received and verified. A payment you have made may take time to appear while it is checked. If you believe a record is wrong, contact the secretariat; corrections are made through recorded adjustments rather than by deleting history.

## Content

Text, photographs and the association’s crest are published with the association’s permission and may not be reused without it.

