## Who we are

Ẹgbẹ́ Bobagunwa Okunrin Akile Ijebu (“the association”) is responsible for the personal information described in this notice. You can contact the association through the [contact page]({{ route('contact') }}).

## What we collect

- **Membership applications:** your name, date of birth, Ijebu town of origin, city of residence, occupation, email address, phone number, the reason you give for applying, and your declarations.
- **Member records:** your membership number, contact details, membership status and the profile details you choose to keep up to date.
- **Financial records:** dues and levies assessed to you, payments you make and how they were applied. The association does not collect bank card details or bank login credentials.
- **Enquiries:** the details you send through the contact form.
- **Security records:** sign-in activity and a keyed fingerprint of the network address used, so that misuse can be detected. Raw network addresses are not stored in our records.

## Why we use it

- To consider membership applications and keep the membership register (legitimate interests of the association and steps you ask us to take).
- To administer dues, levies and payments and keep accurate financial records (contract with members and record-keeping obligations).
- To reply to enquiries and to share association notices and events with members.
- To keep the website and member accounts secure.

## Who can see it

Only officers whose role requires it. Membership officers cannot see financial records unless they also hold a finance role. Members can see only their own records. The association does not sell personal information and does not publish a member directory. The website is hosted by the association’s hosting provider, which processes data on the association’s behalf.

## How long we keep it

Applications, member records and financial records are kept for as long as they are needed for the association’s administration and its record-keeping obligations. Final retention periods are being set by the association and will be stated here.

## Your rights

Under the Nigeria Data Protection Act 2023 you may ask to see the information held about you, ask for corrections, object to certain uses, and ask for information to be deleted where the association has no continuing need or obligation to keep it. Members can correct many details in the member portal. You may also complain to the Nigeria Data Protection Commission.

## Security

Passwords are stored only in hashed form; private pages are not cached; access is limited by role and recorded in an audit history; backups are encrypted.
