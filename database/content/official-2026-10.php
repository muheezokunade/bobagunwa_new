Unarguably, one of Nigeria’s greatest living monarchs, a patriot and nationalist of the highest order, Alaiyeluwa Oba (Dr.) Sikiru Kayode Adetona, the Awujale and paramount Ruler of Ijebu land, has been on the throne for about sixty-six (66) years, having been officially recognised by the then Western Region Government of the Federal Republic of Nigeria on January 4, 1960 and crowned on April 2, 1960, six months before the country attained independence.

The Awujale was born on the 10th day of May 1934 in the formidable town and unique land of Ijebu-Ode, Capital of Ijebu Land, and is thus ninety-one years old. Being a first-class monarch and the longest reigning Awujale in recorded history, his reign has been a monumental success and a pride to the Ijebus of Southwest Nigeria.

He was born as Prince Sikiru Kayode Adetona to the Anikilaya Ogbagba Royal family of Ijebu-Ode. His father was Prince Rufai Adetona, whilst his mother, Alhaja Ajibabi Adetona (née Onashile), who hailed from Ijebu-Igbo, was the aunt of Otuna (Dr.) Mike Adenuga (Jnr.) of Globacom.

Young Prince Adetona attended Baptist School, Ereko, Ijebu-Ode; Ogbere United Primary School, Oke-Agbo, Ijebu-Igbo and Ansar-Ud-Deen School, Ijebu-Ode between 1943 and 1950. For his secondary education, he was at Olu-Iwa (now Adeola Odutola) College, Ijebu-Ode from 1951 to 1956. Between 1957 and 1958, he took appointment with the Audit Department of the Western Region, Ibadan. The charming prince then resigned his appointment in 1958 to pursue further studies in Accountancy in the United Kingdom before he was nominated as the King-Elect and presented formally to the whole world as the new traditional ruler for Ijebu Land on January 18, 1960, by the head of Ijebu-Ode Regency Council, the late Ogbeni-Oja, Chief Timothy Adeola Odutola.

