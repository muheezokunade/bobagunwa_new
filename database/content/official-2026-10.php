Our belief in the core value of Regberegbe in Akile Ijebu gave birth to this noble group in 2016, with palace recognition and Royal blessings by the Awujale of Ijebu Land, His Royal Majesty, Alaiyeluwa, Oba (Dr.) Sikiru Kayode Adetona GCON, CFR, JP, Ogbagba II on the 24th June 2023.

